"""One pair representation shared by additive checked C frontends."""
COMPLEX_LAYOUTS = {
    'complex_f32': {'component': 'float', 'size': 8, 'alignment': 4, 'offsets': {'re': 0, 'im': 4}},
    'complex_f64': {'component': 'double', 'size': 16, 'alignment': 8, 'offsets': {'re': 0, 'im': 8}},
}


def header():
    lines = ['/* Generated by checked interface generators. Do not edit. */',
             '#ifndef ZYNUM_CHECKED_COMPLEX_H', '#define ZYNUM_CHECKED_COMPLEX_H',
             '#include <stddef.h>', '#ifdef __cplusplus',
             '#define ZCC_ASSERT static_assert', '#define ZCC_ALIGNOF alignof', '#else',
             '#define ZCC_ASSERT _Static_assert', '#define ZCC_ALIGNOF _Alignof', '#endif']
    for name, layout in COMPLEX_LAYOUTS.items():
        typ = 'zynum_checked_' + name
        lines += [f'typedef struct {{ {layout["component"]} re, im; }} {typ};',
                  f'ZCC_ASSERT(sizeof({typ}) == {layout["size"]}, "{name} size");',
                  f'ZCC_ASSERT(ZCC_ALIGNOF({typ}) == {layout["alignment"]}, "{name} alignment");']
        lines += [f'ZCC_ASSERT(offsetof({typ}, {field}) == {offset}, "{name}.{field}");'
                  for field, offset in layout['offsets'].items()]
    return '\n'.join(lines + ['#undef ZCC_ASSERT', '#undef ZCC_ALIGNOF', '#endif', ''])
