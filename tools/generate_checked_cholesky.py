"""Generate an optional checked Cholesky frontend over existing admitted calls."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
sys.dont_write_bytecode = True
from checked_cholesky_profile import PROFILE, TARGET, candidate, validate
from checked_complex_wire import header as complex_header

ROOT = Path(__file__).resolve().parents[1]


def render(plan, zig):
    plan = validate(plan)
    # Pin the reviewed conversion/admission bridge, without pretending that this
    # one file proves the whole numerical dependency closure or runtime ABI.
    bridge = ROOT / 'src/checked/implementation.zig'
    if hashlib.sha256(bridge.read_bytes()).hexdigest() != 'bf05e8adfac3a678ab2db7a2b5fa8588a8ebba105ce358d7e8c27e6d238090c5':
        raise ValueError('Checked Cholesky conversion/admission source drift')
    c = ['/* Generated by tools/generate_checked_cholesky.py. Do not edit. */',
         '#ifndef ZYNUM_CHECKED_CHOLESKY_H', '#define ZYNUM_CHECKED_CHOLESKY_H',
         '#include <zynum/checked/checked.h>', '#include <zynum/checked/complex.h>',
         '#define ZYNUM_CHECKED_CHOLESKY_INVALID_HERMITIAN_DIAGONAL INT32_C(15)',
         '/* Column-major; buffer lengths count complex elements, not bytes.',
         ' * Caller owns and may reuse factors across calls. Solve never writes factors.',
         ' * Selected entries must be finite, diagonal imaginary parts exactly zero.',
         ' * Other triangle and padding are ignored and preserved.',
         ' * Argument/finite errors precede mutation. Numerical failure may leave',
         ' * a factor/solve prefix; info is the one-based failure position.',
         ' * Empty systems/zero RHS are validated no-ops. No factor handle is created.',
         ' * Real f32/f64 Cholesky declarations are inherited from checked.h. */',
         '#ifdef __cplusplus', 'extern "C" {', '#endif']
    z = ['// Generated by tools/generate_checked_cholesky.py. Do not edit.',
         'const abi = @import("abi_types.zig");', 'const impl = @import("implementation.zig");',
         'const core = @import("zynum-core");']
    for scalar, layout in plan['complex_layouts'].items():
        native = 'core.lapack.ComplexF32' if scalar == 'complex_f32' else 'core.lapack.ComplexF64'
        sparse = 'core.sparse.ComplexF32' if scalar == 'complex_f32' else 'core.sparse.ComplexF64'
        z += ['comptime {', f'if ({native} != {sparse}) @compileError("one internal complex scalar owner required");',
              f'if (@sizeOf({native}) != {layout["size"]} or @alignOf({native}) != {layout["alignment"]}) @compileError("{scalar} layout");',
              f'if (@offsetOf({native}, "re") != 0 or @offsetOf({native}, "im") != {layout["offsets"]["im"]}) @compileError("{scalar} fields");', '}']
    for row in plan['bindings']:
        ca = [f'{"int32_t" if typ == "i32" else "zynum_checked_" + typ} {name}' for name, typ, _ in row['parameters']]
        za = [f'{name}: {"i32" if typ == "i32" else "abi." + typ}' for name, typ, _ in row['parameters']]
        native = 'core.lapack.ComplexF32' if row['scalar'] == 'complex_f32' else 'core.lapack.ComplexF64'
        c.append('zynum_checked_result ' + row['symbol'] + '(' + ', '.join(ca) + ');')
        args = ', '.join([native, *(name for name, _, _ in row['parameters'])])
        z += ['pub export fn ' + row['symbol'] + '(' + ', '.join(za) + ') callconv(.c) abi.result {',
              'return impl.' + row['adapter'] + '(' + args + ');', '}']
    c += ['#ifdef __cplusplus', '}', '#endif', '#endif']
    source = subprocess.run([zig, 'fmt', '--stdin'], input='\n'.join(z)+'\n', text=True,
                            capture_output=True, check=True).stdout
    return {'include/zynum/checked/complex.h': complex_header(),
            'include/zynum/checked/cholesky.h': '\n'.join(c)+'\n',
            'include/zynum/checked/cholesky_manifest.json': json.dumps(plan, indent=2)+'\n',
            'src/checked/cholesky_exports.zig': source,
            'src/checked/cholesky_status.zig': '// Generated by tools/generate_checked_cholesky.py. Do not edit.\npub const INVALID_HERMITIAN_DIAGONAL: i32 = 15;\n'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', required=True)
    parser.add_argument('--target-contract', required=True)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--zig', default='zig')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        outputs = render(candidate(args.profile, args.target_contract), args.zig)
    except ValueError as error:
        parser.error(str(error))
    if args.check:
        drift = [str(path) for path, content in outputs.items()
                 if not (args.root/path).is_file() or (args.root/path).read_text() != content]
        if drift:
            parser.error('Generated checked Cholesky drift: ' + ', '.join(drift))
    else:
        for path, content in outputs.items():
            target = args.root/path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    print(('Checked' if args.check else 'Generated') + ' four additive complex Cholesky entries; runtime evidence is separate')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
