def _subset_cpp_complex_layout_lines():
    # C++ standard complex has accessor functions, while MKL's default structs
    # have data members. Admit the proven standard type without discarding the
    # exact field/type checks for struct representations.
    return [
        '#include <complex>', '#include <type_traits>', '#include <utility>',
        '#ifndef ZYNUM_LAPACKE_CPP_COMPLEX_LAYOUT_V1',
        '#define ZYNUM_LAPACKE_CPP_COMPLEX_LAYOUT_V1',
        'namespace zynum_lapacke_detail_v1 {',
        'template<class T, class R, class = void>',
        'struct ComplexFields : std::is_same<T, std::complex<R> > {};',
        'template<class T, class R>',
        'struct ComplexFields<T, R, decltype((void)std::declval<T&>().real, (void)std::declval<T&>().imag, void())>',
        '  : std::integral_constant<bool, std::is_standard_layout<T>::value &&',
        '      std::is_same<decltype(std::declval<T&>().real), R>::value &&',
        '      std::is_same<decltype(std::declval<T&>().imag), R>::value &&',
        '      offsetof(T, real) == 0 && offsetof(T, imag) == sizeof(R)> {};',
        '}', '#endif',
    ]


def subset_outputs(profile, binding_set, target_contract, zig="zig"):
    """Select an exact accepted finite set before rendering, formatting or writes."""
    if isinstance(binding_set, str) and binding_set.startswith('sparse-'):
        from generate_sparse_abi import outputs as sparse_outputs
        return sparse_outputs(profile, binding_set, target_contract, zig)
    plan = select_binding_set(profile, binding_set, target_contract)
    return _render_subset(plan, zig)


