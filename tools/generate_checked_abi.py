def _render_subset(plan, zig):
    profile, binding_set = plan["profile"], plan["set"]
    # This branch has only two reviewed width models and one native target.
    with_qr = any(b['operation'].startswith('qr.') for b in plan['bindings'])
    standalone_qr = binding_set == 'geqrf-ormqr-unmqr-ordinary-lp64-v1'
    with_hermitian = any(b['operation'].startswith('hermitian.') for b in plan['bindings'])
    standalone_hermitian = binding_set == 'hermitian-eigen-ordinary-lp64-v1'
    wide = profile == 'mkl2026.ilp64'
    wire, internal, byte_count = ('c_longlong', 'i64', 8) if wide else ('c_int', 'i32', 4)
    suffix = 'ilp64' if wide else 'lp64'
    with_lu = binding_set in ('potrf-potrs-getrf-getrs-ordinary-lp64-v1',
                              'potrf-potrs-getrf-getrs-ordinary-ilp64-v1')
    with_gelsd = any(b['operation'] == 'least_squares.rank_revealing' for b in plan['bindings'])
    with_gesvd = any(b['operation'] == 'svd.decompose' for b in plan['bindings'])
    with_posv = any(b['operation'] == 'cholesky.driver' for b in plan['bindings'])
    with_trtrs = any(b['operation'] == 'triangular.solve' for b in plan['bindings'])
    with_trtri = any(b['operation'] == 'triangular.inverse' for b in plan['bindings'])
    with_getri = any(b['operation'] == 'lu.inverse' for b in plan['bindings'])
    with_complex_gelsd = any(b['operation'] == 'least_squares.rank_revealing_complex' for b in plan['bindings'])
    with_stev = '-stev-' in binding_set
    with_gesv = '-gesv-' in binding_set
    with_lu = with_lu or with_gesv
    family = 'POTRF_POTRS_GETRF_GETRS_GESV_STEV_GELSD' if with_gelsd else 'POTRF_POTRS_GETRF_GETRS_GESV_STEV' if with_stev else 'POTRF_POTRS_GETRF_GETRS_GESV' if with_gesv else 'POTRF_POTRS_GETRF_GETRS' if with_lu else 'POTRF_POTRS'
    if standalone_hermitian:
        family = 'HERMITIAN_EIGEN'
    elif with_hermitian:
        family += '_HEEV_HEGV'
    if standalone_qr: family = 'GEQRF_ORMQR_UNMQR'
    elif with_qr: family += '_GEQRF_ORMQR_UNMQR'
    if with_complex_gelsd: family = 'COMPLEX_GELSD' if len(plan['bindings']) == 4 else family + '_COMPLEX_GELSD'
