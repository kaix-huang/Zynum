def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--zig', default='zig')
    parser.add_argument('--profile', default=DEFAULT_PROFILE,
                        help='Interface profile; only checked-v1 is ready for generation')
    parser.add_argument('--binding-set', help='Explicit finite standard binding set; requires --target-contract')
    parser.add_argument('--target-contract', help='Explicit reviewed target contract; requires --binding-set')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        if args.binding_set is None and args.target_contract is None:
            generated = outputs(args.zig, args.profile)
        else:
            if not args.binding_set or not args.target_contract:
                raise ProfileError('Finite generation requires both --binding-set and --target-contract')
            generated = subset_outputs(args.profile, args.binding_set, args.target_contract, args.zig)
    except ProfileError as error:
        parser.error(str(error))
    for name, content in generated.items():
        path = args.root / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit('Generated drift: ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.binding_set is None:
        print(('Checked' if args.check else 'Generated') + ' 6 checked ABI outputs, 8 functions')
    else:
        manifest = json.loads(next(value for path, value in generated.items() if path.endswith('/abi_manifest.json')))
        count = len(manifest['plan']['symbols'])
        print(('Checked' if args.check else 'Generated') + f' 4 finite interface outputs, {count} functions; full profile not ready')

if __name__ == '__main__':
    main()
