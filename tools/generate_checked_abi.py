def outputs(zig="zig", profile=DEFAULT_PROFILE):
    selected = select_profile(profile)
    OBJECT_SUPPORT_SYMBOLS, ABI_REVISION, POINTER_BITS, PRIMITIVE_LAYOUT, PREFIX, STATUS, FLAGS, STRUCTS, FUNCTIONS = (
        selected[key] for key in ('OBJECT_SUPPORT_SYMBOLS', 'ABI_REVISION', 'POINTER_BITS', 'PRIMITIVE_LAYOUT',
                                 'PREFIX', 'STATUS', 'FLAGS', 'STRUCTS', 'FUNCTIONS'))
    C = {'i32':'int32_t','i64':'int64_t','f32':'float','f64':'double','ptr':'void *','const_ptr':'const void *'}
    Z = {'i32':'i32','i64':'i64','f32':'f32','f64':'f64','ptr':'?*anyopaque','const_ptr':'?*const anyopaque'}
    F = {'i32':'integer(c_int32_t)','i64':'integer(c_int64_t)','f32':'real(c_float)', 'f64':'real(c_double)', 'ptr':'type(c_ptr)','const_ptr':'type(c_ptr)'}
    type_layout = dict(PRIMITIVE_LAYOUT)
    for name in STRUCTS:
        C[name] = PREFIX+name
        Z[name] = name
        F[name] = 'type('+PREFIX+name+')'
    layouts = {}
    c = ['/* Generated by tools/generate_checked_abi.py from tools/checked_abi_schema.py. Do not edit. */',
         '#ifndef ZYNUM_CHECKED_H', '#define ZYNUM_CHECKED_H',
         '#include <stdint.h>', '#include <stddef.h>', '#ifdef __cplusplus', 'extern "C" {', '#define ZC_ASSERT static_assert', '#define ZC_ALIGNOF alignof', '#else', '#define ZC_ASSERT _Static_assert', '#define ZC_ALIGNOF _Alignof', '#endif',
         'ZC_ASSERT(sizeof(void *) == 8, "Checked ABI requires 64-bit pointers");']
    z = ['// Generated by tools/generate_checked_abi.py from tools/checked_abi_schema.py. Do not edit.']
    f = ['! Generated by tools/generate_checked_abi.py from tools/checked_abi_schema.py. Do not edit.',
         'module zynum_checked', '  use, intrinsic :: iso_c_binding', '  implicit none']
    c.append(f'#define ZYNUM_CHECKED_ABI_REVISION INT32_C({ABI_REVISION})')
    for key,val in {**STATUS,**FLAGS}.items():
        c.append(f'#define ZYNUM_CHECKED_{key} INT32_C({val})')
        z.append(f'pub const {key}: i32 = {val};')
        f.append(f'  integer(c_int32_t), parameter :: ZYNUM_CHECKED_{key} = {val}_c_int32_t')
    for name,fields in STRUCTS.items():
        offset, alignment, offsets = 0, 1, {}
        for key, typ in fields:
            size, field_alignment = type_layout[typ]
            alignment = max(alignment, field_alignment)
            offset = (offset + field_alignment - 1) // field_alignment * field_alignment
            offsets[key] = offset
            offset += size
        size = (offset + alignment - 1) // alignment * alignment
        type_layout[name] = (size, alignment)
        layout = {'size': size, 'alignment': alignment, 'offsets': offsets}
        layouts[name] = layout
        c += ['typedef struct {']+[f'    {C[typ]} {key};' for key,typ in fields]+[f'}} {C[name]};', f'ZC_ASSERT(sizeof({C[name]}) == {layout["size"]}, "{name} size");']
        c += [f'ZC_ASSERT(ZC_ALIGNOF({C[name]}) == {layout["alignment"]}, "{name} alignment");']
        c += [f'ZC_ASSERT(offsetof({C[name]}, {key}) == {off}, "{name}.{key} offset");' for key,off in layout['offsets'].items()]
        z += [f'pub const {name} = extern struct {{']+[f'    {key}: {Z[typ]},' for key,typ in fields]+['};']
        f += [f'  type, bind(C) :: {C[name]}']+[f'    {F[typ]} :: {key}' for key,typ in fields]+[f'  end type {C[name]}']
    z += ['comptime {', '    if (@sizeOf(usize) != 8) @compileError("Checked ABI requires 64-bit pointers");']
    for name,layout in layouts.items():
        z += [f'    if (@sizeOf({name}) != {layout["size"]} or @alignOf({name}) != {layout["alignment"]}) @compileError("{name} layout");']
        z += [f'    if (@offsetOf({name}, "{key}") != {off}) @compileError("{name}.{key} offset");' for key,off in layout['offsets'].items()]
    z += ['}']
    exports = ['// Generated by tools/generate_checked_abi.py from tools/checked_abi_schema.py. Do not edit.', 'const abi = @import("abi_types.zig");', 'const impl = @import("implementation.zig");']
    f += ['  interface']
    for name,args,body in FUNCTIONS:
        full = PREFIX+name
        c += [f'{C["result"]} {full}('+', '.join(f'{C[t]} {n}' for n,t in args)+');']
        exports += [f'pub export fn {full}('+', '.join(f'{n}: '+(Z[t] if t not in STRUCTS else 'abi.'+t) for n,t in args)+') callconv(.c) abi.result {', f'    return impl.{body};', '}']
        # Wrapping keeps standard free-form Fortran lines <=132 columns.
        f += [f'    function {full}('+', '.join(n for n,_ in args)+') &',
              f'        bind(C, name="{full}") result(out)', '      import']
        f += [f'      {F[t]}, value :: {n}' for n,t in args]
        f += [f'      {F["result"]} :: out', f'    end function {full}']
    c += ['#undef ZC_ALIGNOF', '#undef ZC_ASSERT','#ifdef __cplusplus','}', '#endif','#endif']
    f += ['  end interface', 'contains', '  logical function zynum_checked_layout_ok() result(ok)']
    f += [f'    {F[name]}, target :: v_{name}' for name in STRUCTS]
    f += ['    ok = .true.']
    for name,layout in layouts.items():
        f += [f'    ok = ok .and. c_sizeof(v_{name}) == {layout["size"]}_c_size_t']
        for key,off in layout['offsets'].items():
            f += [f'    ok = ok .and. transfer(c_loc(v_{name}%{key}), 0_c_intptr_t) - &', f'      transfer(c_loc(v_{name}), 0_c_intptr_t) == {off}_c_intptr_t']
    f += ['  end function zynum_checked_layout_ok', 'end module zynum_checked']
    result = {'include/zynum/checked/checked.h':'\n'.join(c)+'\n', 'src/checked/abi_types.zig':'\n'.join(z)+'\n', 'src/checked/exports.zig':'\n'.join(exports)+'\n', 'include/zynum/checked/checked.f90':'\n'.join(f)+'\n', 'include/zynum/checked/abi_manifest.json':json.dumps({'schema':1,'schema_id':'zynum-checked-abi-v1','abi_revision':ABI_REVISION,'stability':'experimental','target_pointer_bits':POINTER_BITS,'export_count':len(FUNCTIONS),'object_support_symbols':OBJECT_SUPPORT_SYMBOLS,'layouts':layouts,'statuses':STATUS,'flags':FLAGS,'exports':[{'name':PREFIX+n,'args':a,'result':'result'} for n,a,_ in FUNCTIONS]},indent=2)+'\n'}
    result["src/checked/exports.def"] = "LIBRARY zynum_checked\nEXPORTS\n" + "".join("    " + PREFIX + name + "\n" for name, _, _ in FUNCTIONS)
    for name in ("src/checked/abi_types.zig", "src/checked/exports.zig"):
        result[name] = subprocess.run([zig, "fmt", "--stdin"], input=result[name], text=True, capture_output=True, check=True).stdout
    for name in result:
        prefix = "!" if name.endswith(".f90") else ";" if name.endswith(".def") else "//"
        if not name.endswith(".json"):
            license = f"{prefix} Copyright (C) 2026 Zynum contributors\n{prefix} SPDX-License-Identifier: LGPL-3.0-or-later\n\n"
            result[name] = license + result[name]
    return result


